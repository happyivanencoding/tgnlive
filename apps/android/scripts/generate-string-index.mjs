import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// A compile-time resource index, not reflection. Regenerate after adding shared UI keys.
const android = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const baseFile = path.join(android, 'app/src/main/res/values/strings.xml');
const names = [...fs.readFileSync(baseFile, 'utf8').matchAll(/<string\s+name="([a-zA-Z0-9_]+)"/g)].map(match => match[1]);
if (!names.length || new Set(names).size !== names.length) throw new Error('Missing or duplicate base string resource');
for (const lang of ['en', 'fr', 'es', 'ar']) {
  const localized = fs.readFileSync(path.join(android, `app/src/main/res/values-${lang}/strings.xml`), 'utf8');
  const found = [...localized.matchAll(/<string\s+name="([a-zA-Z0-9_]+)"/g)].map(match => match[1]);
  if (new Set(found).size !== found.length || found.length !== names.length || names.some(name => !found.includes(name))) {
    throw new Error(`String key mismatch for ${lang}; all five languages must ship together.`);
  }
}
const result = `package com.thegreatnovel.tgnlive\n\n// Generated by scripts/generate-string-index.mjs from the five-language UI resources.\n// Static R.string references retain compile-time checks and work with resource shrinking.\ninternal object NativeStringResources {\n    val ids = mapOf(\n${names.map(name => `        "${name}" to R.string.${name}`).join(',\n')}\n    )\n}\n`;
const target = path.join(android, 'app/src/main/java/com/thegreatnovel/tgnlive/NativeStringResources.kt');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== result) throw new Error('Resource index is stale; run this script without --check.');
} else {
  fs.writeFileSync(target, result);
}
console.log(JSON.stringify({check: process.argv.includes('--check'), languageCount: 5, keysPerLanguage: names.length, status: 'PASS_RESOURCE_KEYS_ONLY'}));
