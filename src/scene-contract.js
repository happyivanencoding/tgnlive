export function liveSceneContract(game) {
  const recent = game.turns.slice(-3);
  const samePlace = recent.length >= 3 && !recent.some(t => (t.changes || []).some(c => /所在|抵达|位置/.test(c)));
  return `当轮执行准则：先兑现本次具体行动的结果，再展开新局势；成功、部分成功或失败都必须使局面发生清楚变化。不得连续把出口、暗门、谈判或夺物改成“又发现一重阻碍”来拖住读者；脱险后允许真正脱险，守卫不能每次瞬移追上。把紧张、喘息、交易、探索和短暂安心写出节奏差异。不要在正文尾部再用“他可以A也可以B”复述按钮；正文停在人物或事物的具体变化上。
物理与记忆：触碰什么，就只能取得该对象自身留下的有限信息；烬息不是遥感、读心或预知，触摸自己的铜钱不能读取远处药柜；没有余温或相应痕迹可以无收获。普通遗物不得因方便剧情突然拥有新功能。已关的门不能无因重新开高，已写明的伤处不能从肩头换到腹部，人物离开后不能无因到场。旧计划只是可能性，旧开局不是必须重复的场景。
所有权与成长：正文中交给玩家、花掉、吃掉、失去的关键物品和钱，必须在同轮delta中增减；别人持有的物品不自动归玩家。玩家输入声称“先前你给我的药液”不代表此物真的存在；若此前只有止血散，就说明差异并用实际持有的物品行动，不要凭空补发道具。临时借用要写清归还与否。玩家因风险、谈判、训练赢得了可用资源、报酬、掌握能力或盟友，应及时兑现，不要只发下一条线索。不要无端送境界进度；当确实有修炼或能力掌握改善时，写出过程与新用途并记录小幅进度。若玩家选择调查而非修炼，信息收获本身即可，不必强行升级。
只记新发生或确实确认的事实；传闻、推断、NPC的说法须注明来源，不能升级成世界真相。${samePlace ? '最近数回合仍处于近似场景：特别检查本次行动是否获得了阶段性结果，避免重复逼近/敲门/耳鸣。' : ''}`;
}
